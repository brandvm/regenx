// Write CLASSES.md: every class in the new-classes CSS files that Webflow
// doesn't have yet, named the way the Designer shows it (conventions.md §3),
// grouped by the comment that introduces each group.  pnpm classes
//
// A group starts at a comment whose first line reads "Name — what it is for."
// Combos (.card.is-active) are listed with their base; classes whose group
// comment or rule comment says `js-state` are marked JS state.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = fs.readdirSync(path.join(root, 'src/css')).filter((f) => /^new-classes.*\.css$/.test(f)).sort();
const existing = new Set(JSON.parse(fs.readFileSync(path.join(root, 'webflow-snapshot/styles.json'), 'utf8')).map((s) => s.selector));
const UPPER = new Set(['cta', 'sr', 'ui', 'sg', 'faq', 'seo']);

// card-body → Card Body; is-active → Is Active; s-bg → S Bg.
const webflowName = (cls) => cls.split('-').map((w) => (UPPER.has(w) || w.length === 1 ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1))).join(' ');

const out = [
  '# Classes: Webflow names',
  '',
  'Every class the build adds to Webflow, generated by `pnpm classes` from',
  'the prototype CSS. Type the name exactly as written; Webflow turns it into',
  'the CSS class in brackets. **Combo** = add it on top of the base class.',
  '**JS state** = set by a script; create it in the Designer only if the',
  'Designer styles it (otherwise it lives in repo CSS).',
  '',
];
let total = 0;
for (const file of FILES) {
  const css = fs.readFileSync(path.join(root, 'src/css', file), 'utf8');
  out.push(`## ${file}`, '');
  let group = null;
  const seen = new Set();
  // Walk comments and rule preludes in order.
  for (const m of css.matchAll(/\s*(?:\/\*([\s\S]*?)\*\/|([^{}]+?)\{)/g)) {
    if (m[1] !== undefined) {
      const first = m[1].trim().split('\n')[0].trim();
      const g = first.match(/^([A-Z][\w |]*?)\s+[—-]\s+(.+)$/);
      if (g && !first.startsWith('repo-css')) {
        group = { title: g[1], note: g[2], js: /js-state/.test(m[1]) };
        out.push(`### ${group.title}`, group.note, '');
      }
      continue;
    }
    for (let sel of m[2].split(',')) {
      sel = sel.trim();
      if (!/^(?:[a-z]+)?(\.[a-z][\w-]*)+$/.test(sel)) continue; // plain class chains only
      const full = '.' + sel.replace(/^[a-z]+(?=\.)/, '').replace(/^\./, '');
      if (existing.has(full) || seen.has(full)) continue;
      seen.add(full);
      const parts = full.slice(1).split('.');
      const label = parts.map(webflowName).join(' ');
      const kind = group?.js ? ' · JS state' : parts.length > 1 ? ' · combo' : '';
      out.push(`- **${label}** (\`${full}\`)${kind}`);
      total++;
    }
  }
  out.push('');
}
fs.writeFileSync(path.join(root, 'CLASSES.md'), out.join('\n').replace(/\n{3,}/g, '\n\n'));
console.log(`CLASSES.md: ${total} classes`);
