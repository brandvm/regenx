// Build the prototype's CSS, and as much of the snapshot as can be
// recovered, from the CSS a Webflow site publishes. The fallback for when
// no Webflow connector is available; the MCP snapshot (README › Webflow
// snapshot) replaces it as soon as one is.
//   pnpm css:published [https://<site>.webflow.io] [--crawl] [--max 300] [--css file.css …] [--no-snapshot]
// The address comes from the argument, or from `stagingUrl` in the repo's
// webflow-build.config.json. Only GET requests; nothing is written to
// Webflow. A site with per-page CSS is read page by page and the files are
// merged in an order every page agrees with (published-css.mjs).
//
// Writes:
//   src/css/webflow-base.css   what Webflow ships itself: normalize, w-*,
//                              the site's @font-face (linked first in
//                              partials/head.html; added if missing)
//   src/css/tokens.css         :root, every variable as published
//   src/css/webflow.css        every site style, in the published order
//   webflow-snapshot/variables.json, styles.json   recovered (see below)
//   webflow-snapshot/source.json   where it came from, what was assumed and
//                              skipped; while it exists `pnpm css` refuses to
//                              run (it would rebuild the CSS from guesses)
//
// The CSS is exact. The snapshot is a reconstruction, good enough for the
// style guide, the class list and check:snapshot. It CANNOT recover:
//   - Designer names: classes, variables, groups and collections are
//     re-derived from the CSS slug (`g-nav-link` → "G Nav Link",
//     `--_colors---brand--ink` → Colors › "Brand/Ink"). Case, spaces and
//     punctuation are lost; unprefixed variables (`--<group>--<name>`) go to
//     a collection named "Base collection".
//   - Mode names: breakpoint modes are called Tablet, Mobile Landscape and
//     Mobile; a mode a class sets is named after that class ("Is Dark").
//   - Breakpoint auto-modes vs a mode set on the Body tag per breakpoint:
//     both publish as `body { --var… }` inside the media query. Written as
//     `breakpointModes` on the collection (the template's convention).
//   - Which class of a chain is the base and which the combo (taken from the
//     selector order); component variant names (`:where(.w-variant-<id>)`,
//     kept as their own entries).
//   - Classes with no properties (pure script or attribute hooks) and
//     properties left at Webflow's default: they publish nothing.
//   - Interactions (IX2/IX3), and element-level styles (`#w-node-…` grid
//     placement): skipped.
//   - Variable types where the value is ambiguous (`140%` Size or
//     Percentage; a font stack keeps its first family).
//   - Deleted variables that styles still read (published as
//     `--name<deleted|variable-…>`): kept in "Base collection" as
//     "<Name> (deleted …)" so the styles still render.
//   - Values as typed: they are as Webflow minified them (`#fff`, `.5em`).
//   - Selectors a Webflow style can't be (`.a .b`, two states at once) stay
//     in webflow.css and are listed in source.json, not in styles.json.
import fs from 'node:fs';
import path from 'node:path';
import { root, config, args } from './lib.mjs';
import { readPublished, declarations, selectors, serialize } from './published-css.mjs';

const { flags, values, pos } = args(['--max', '--css']);
const files = process.argv.slice(2).flatMap((a, i, all) => (all[i - 1] === '--css' ? [a] : []));
const site = pos[0] ?? config().stagingUrl;
if (!site && !files.length) { console.error('Which site? pnpm css:published https://<site>.webflow.io (or set stagingUrl in webflow-build.config.json, or pass --css <file>).'); process.exit(1); }

let pub;
try { pub = await readPublished(site, { files, crawl: flags.has('--crawl'), max: +(values.max ?? 300), log: console.log }); }
catch (e) { console.error(e.message); process.exit(1); }
if (!pub.root.length) { console.error('No :root variables in the published CSS: not a Webflow stylesheet, or a site without variables.'); process.exit(1); }

// ---------- 1. the CSS, exactly as published ----------
const write = (f, data) => fs.writeFileSync(path.join(root, f), typeof data === 'string' ? data : JSON.stringify(data, null, 1) + '\n');
const from = files.length ? files.join(', ') : `${site} (${pub.sheets.length} stylesheet${pub.sheets.length === 1 ? '' : 's'}${pub.perPage ? `, per-page CSS from ${pub.pages.length} pages` : ''})`;
const header = (what) => `/* GENERATED by \`pnpm css:published\` from the CSS Webflow publishes:\n   ${from}, ${new Date().toISOString().slice(0, 10)}.\n   ${what} Never edit: change Webflow, publish, run it again. */\n\n`;
write('src/css/webflow-base.css', header("What Webflow ships itself (normalize, w-*, the site's @font-face).") + serialize(pub.base) + '\n');
write('src/css/tokens.css', header('Every variable, on :root.') + `:root {\n${pub.root.map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n`);
write('src/css/webflow.css', header('Every site style, in the published order.') + serialize(pub.site) + '\n');

// webflow-base.css loads first, before tokens.css.
const headFile = path.join(root, 'partials/head.html');
if (fs.existsSync(headFile)) {
  const head = fs.readFileSync(headFile, 'utf8');
  if (!head.includes('/src/css/webflow-base.css')) {
    fs.writeFileSync(headFile, head.replace('<link rel="stylesheet" href="/src/css/tokens.css">', '<link rel="stylesheet" href="/src/css/webflow-base.css">\n<link rel="stylesheet" href="/src/css/tokens.css">'));
    console.log('partials/head.html: linked src/css/webflow-base.css before tokens.css');
  }
}
console.log(`webflow-base.css ${pub.base.length} rules; tokens.css ${pub.root.length} variables; webflow.css ${pub.site.length} top-level rules`);
if (flags.has('--no-snapshot')) process.exit(0);

// ---------- 2. variables ----------
const title = (slug) => slug.split('-').filter(Boolean).map((w) => (/^\d/.test(w) ? w : w[0].toUpperCase() + w.slice(1))).join(' ');
const DEFAULT_COLLECTION = 'Base collection';
const BP_MODES = { medium: 'Tablet', small: 'Mobile Landscape', tiny: 'Mobile' };
const BP_DOWN = ['medium', 'small', 'tiny'];
const unescape = (n) => n.replace(/\\(.)/g, '$1');
function nameVariable(cssName) {
  const raw = unescape(cssName);
  const deleted = raw.match(/^--(.+)<deleted\|variable-([0-9a-f]+)>$/);
  if (deleted) return { collection: DEFAULT_COLLECTION, name: `${deleted[1].split('--').map(title).join('/')} (deleted ${deleted[2]})` };
  const m = raw.match(/^--_([a-z0-9-]+?)---(.+)$/);
  if (m) return { collection: title(m[1]), name: m[2].split('--').map(title).join('/') };
  return { collection: DEFAULT_COLLECTION, name: raw.slice(2).split('--').map(title).join('/') };
}
const COLOR = /^(#[0-9a-f]{3,8}|rgba?\(|hsla?\(|color-mix\(|oklch\(|oklab\(|transparent$|currentcolor$|white$|black$)/i;
function typeAndValue(v) {
  if (COLOR.test(v)) return ['Color', v];
  let m = v.match(/^(-?[\d.]+)(px|em|rem|vw|vh|svh|dvh|lvh|ch)$/);
  if (m) return ['Size', { value: +m[1], unit: m[2] }];
  m = v.match(/^(-?[\d.]+)%$/);
  if (m) return ['Percentage', +m[1]];
  if (/^-?[\d.]+$/.test(v)) return ['Number', +v];
  if (/"|,\s*(sans-serif|serif|monospace|system-ui)$/.test(v)) return ['FontFamily', v.split(',')[0].replace(/^["']|["']$/g, '').trim()];
  if (/^calc\(/.test(v)) return ['Size', v];
  return ['Custom', v];
}

const collections = new Map(); // name → { collection, modes, variables }
const byCss = new Map(); // css name → { collection, variable }
for (const [cssName] of pub.root) {
  const { collection, name } = nameVariable(cssName);
  if (!collections.has(collection)) collections.set(collection, { collection, modes: ['Base'], variables: [] });
  const variable = { name, type: null, cssName, values: {} };
  collections.get(collection).variables.push(variable);
  byCss.set(cssName, { collection, variable });
}
const ref = (cssName) => { const e = byCss.get(cssName); return e ? `${e.collection}/${e.variable.name}` : null; };
function setValue(variable, mode, v) {
  const alias = v.match(/^var\((--[^,)]+)\)$/);
  if (alias && byCss.has(alias[1])) { (variable.alias ??= {})[mode] = ref(alias[1]); delete variable.values[mode]; return; }
  const [type, value] = typeAndValue(v);
  variable.values[mode] = value;
  if (variable.alias) delete variable.alias[mode];
  (variable._types ??= []).push(type);
}
const copyMode = (variable, from, to) => {
  if (variable.values[to] !== undefined || variable.alias?.[to]) return;
  if (variable.alias?.[from]) (variable.alias ??= {})[to] = variable.alias[from];
  else if (variable.values[from] !== undefined) variable.values[to] = variable.values[from];
};
const addMode = (c, mode) => { const coll = collections.get(c); if (!coll.modes.includes(mode)) coll.modes.push(mode); };
for (const [cssName, v] of pub.root) setValue(byCss.get(cssName).variable, 'Base', v);

const BP_OF = (at) => {
  const max = at.match(/max-width:\s*(\d+)px/)?.[1];
  const min = at.match(/min-width:\s*(\d+)px/)?.[1];
  return { 991: 'medium', 767: 'small', 479: 'tiny' }[max] ?? { 1280: 'large', 1440: 'xl', 1920: 'xxl' }[min] ?? null;
};
const report = { skippedSelectors: [], skippedAtRules: [], modesFromClasses: {} };

// Breakpoint modes: `body` (or :root) re-declaring variables in a media query.
const breakpointModes = {}; // collection → { medium: 'Tablet', … }
for (const r of pub.site) {
  if (!r.rules) continue;
  const bp = BP_OF(r.at);
  if (!BP_MODES[bp]) continue;
  for (const inner of r.rules) {
    if (inner.sel !== 'body' && inner.sel !== ':root') continue;
    for (const [cssName, v] of declarations(inner.body)) {
      const e = byCss.get(cssName);
      if (!e) continue;
      setValue(e.variable, BP_MODES[bp], v);
      (breakpointModes[e.collection] ??= {})[bp] = BP_MODES[bp];
    }
  }
}
// A breakpoint mode publishes only what changes; the rest is the cascade
// (Tablet from Base, Mobile Landscape from Tablet, Mobile from that).
for (const [c, bps] of Object.entries(breakpointModes)) {
  const coll = collections.get(c);
  let prev = 'Base';
  for (const bp of BP_DOWN) {
    if (!bps[bp]) { bps[bp] = BP_MODES[bp]; }
    addMode(c, BP_MODES[bp]);
    for (const v of coll.variables) copyMode(v, prev, BP_MODES[bp]);
    prev = BP_MODES[bp];
  }
  coll.breakpointModes = bps;
}

// ---------- 3. styles ----------
const STATE_CLASSES = { 'w--current': 'current', 'w--redirected-checked': 'redirected-checked', 'w--redirected-focus': 'redirected-focus' };
const className = (slug) => (slug.includes('_') ? slug : slug.split('-').filter(Boolean).map((w) => (/^\d/.test(w) ? w : w.length === 1 ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1))).join(' '));
const SHORTHAND = {
  padding: ['padding-top', 'padding-right', 'padding-bottom', 'padding-left'],
  margin: ['margin-top', 'margin-right', 'margin-bottom', 'margin-left'],
  inset: ['top', 'right', 'bottom', 'left'],
};
// Space-separated parts; minified CSS glues `var(--a)var(--b)` together.
function valueParts(v) {
  const parts = []; let depth = 0, cur = '';
  for (const c of v) {
    if (c === '(') depth++;
    if (c === ')') { depth--; cur += c; if (!depth) { parts.push(cur); cur = ''; } continue; }
    if (/\s/.test(c) && !depth) { if (cur) parts.push(cur); cur = ''; continue; }
    cur += c;
  }
  if (cur) parts.push(cur);
  return parts;
}
function expand(prop, value) {
  const longs = SHORTHAND[prop];
  if (!longs || /!important/.test(value)) return [[prop, value]];
  const p = valueParts(value);
  if (p.length < 1 || p.length > 4) return [[prop, value]];
  const [t, r = t, b = t, l = r] = p;
  return longs.map((k, i) => [k, [t, r, b, l][i]]);
}
const bind = (v) => { const m = v.match(/^var\((--[^,)]+)\)$/); const r = m && ref(m[1]); return r ? `var:${r}` : v; };

function parseSelector(sel) {
  if (sel.includes('#') || sel.includes('[')) return null; // element-level, attribute selectors
  const variant = sel.match(/:where\(\.w-variant-([0-9a-f-]+)\)$/)?.[1];
  const s = variant ? sel.replace(/:where\(\.w-variant-[0-9a-f-]+\)$/, '') : sel;
  // A tag inside a class (`.rich-text a:hover`): Webflow's nested selector.
  const nested = s.match(/^((?:\.[\w-]+)+) ([a-z][a-z0-9]*)((?:::?[a-z-]+)?)$/);
  if (nested && !variant) {
    const [, chain, tag, pseudo] = nested;
    return { selector: `${chain} ${tag}`, name: `${className(chain.slice(1).split('.').pop())} › ${tag}`, state: pseudo ? pseudo.replace(/^::?/, '') : null };
  }
  const m = s.match(/^([a-z][a-z0-9]*|(?:\.[\w-]+)+)((?:::?[a-z-]+(?:\([^)]*\))?)*)$/);
  if (!m) return null;
  let [, base, pseudos] = m;
  let state = null;
  if (base.startsWith('.')) {
    const parts = base.slice(1).split('.');
    const st = parts.filter((p) => STATE_CLASSES[p]);
    if (st.length > 1) return null;
    if (st.length) state = STATE_CLASSES[st[0]];
    base = '.' + parts.filter((p) => !STATE_CLASSES[p]).join('.');
  }
  const ps = (pseudos.match(/::?[a-z-]+(?:\([^)]*\))?/g) ?? []).map((p) => p.replace(/^::?/, ''));
  if (ps.length + (state ? 1 : 0) > 1) return null; // one state per key
  if (ps.length) state = ps[0];
  const last = base.startsWith('.') ? base.slice(1).split('.').pop() : base;
  let name = base.startsWith('.') ? className(last) : base;
  let selector = base;
  if (variant) { selector = `${base}:where(.w-variant-${variant})`; name = `${name} [variant ${variant.slice(0, 8)}]`; }
  return { selector, name, state, variant };
}

// A class that re-declares a collection's variables sets a mode on it. Each
// distinct set of values is one mode, named after the first class using it.
const modeSets = new Map(); // collection → Map(signature → mode name)
function modeFor(collection, decls, label) {
  const sig = JSON.stringify(decls.sort());
  const sets = modeSets.get(collection) ?? modeSets.set(collection, new Map()).get(collection);
  if (sets.has(sig)) return sets.get(sig);
  let mode = label;
  const coll = collections.get(collection);
  for (let n = 2; coll.modes.includes(mode); n++) mode = `${label} ${n}`;
  sets.set(sig, mode);
  addMode(collection, mode);
  for (const [cssName, v] of decls) setValue(byCss.get(cssName).variable, mode, v);
  for (const v of coll.variables) copyMode(v, 'Base', mode);
  (report.modesFromClasses[collection] ??= []).push(`${mode} (${label})`);
  return mode;
}

const styles = new Map();
function addRule(sel, body, bp) {
  for (const one of selectors(sel)) {
    // Webflow's script-driven copies of :focus-visible and :focus-within.
    if (/\[data-wf-focus-(visible|within)\]/.test(one)) continue;
    const p = parseSelector(one);
    if (!p) { report.skippedSelectors.push(`${bp} ${one}`); continue; }
    const entry = styles.get(p.selector) ?? { name: p.selector === 'body' ? 'body' : p.name, selector: p.selector, properties: {} };
    if (p.variant) entry.variant = p.variant;
    styles.set(p.selector, entry);
    const key = p.state ? `${bp}:${p.state}` : bp;
    const props = (entry.properties[key] ??= {});
    const vars = {};
    for (const [prop, value] of declarations(body)) {
      if (prop.startsWith('--')) { const e = byCss.get(prop); if (e) (vars[e.collection] ??= []).push([prop, value]); continue; }
      for (const [k, v] of expand(prop, value)) props[k] = bind(v);
    }
    // body or :root at a breakpoint: the breakpoint modes, read above.
    const bodyAtBp = (p.selector === 'body' || p.selector === ':root') && BP_MODES[bp];
    const label = p.name[0].toUpperCase() + p.name.slice(1);
    if (!bodyAtBp) for (const [c, decls] of Object.entries(vars)) {
      ((entry.variableModes ??= {})[key] ??= {})[c] = modeFor(c, decls, label);
    }
    if (!Object.keys(props).length) delete entry.properties[key];
  }
}
for (const r of pub.site) {
  if (r.sel) addRule(r.sel, r.body, 'main');
  else if (r.rules && /^@media/.test(r.at)) {
    const bp = BP_OF(r.at);
    if (!bp) { report.skippedAtRules.push(r.at); continue; }
    for (const inner of r.rules) if (inner.sel) addRule(inner.sel, inner.body, bp); else report.skippedAtRules.push(`${r.at} › ${inner.at}`);
  } else report.skippedAtRules.push(r.at);
}

// Types: an alias takes its target's type.
const find = (refName) => { const [c, ...rest] = refName.split('/'); return collections.get(c)?.variables.find((x) => x.name === rest.join('/')); };
const typeOf = (variable, seen = new Set()) => {
  if (variable.type) return variable.type;
  if (seen.has(variable)) return 'Custom';
  seen.add(variable);
  const own = variable._types?.find((t) => t !== 'Custom') ?? variable._types?.[0];
  if (own) return own;
  const target = Object.values(variable.alias ?? {})[0];
  const tv = target && find(target);
  return tv ? typeOf(tv, seen) : 'Custom';
};
for (const c of collections.values()) for (const v of c.variables) v.type = typeOf(v);
for (const c of collections.values()) for (const v of c.variables) {
  delete v._types;
  if (!Object.keys(v.values).length) delete v.values;
  if (v.alias && !Object.keys(v.alias).length) delete v.alias;
}

// ---------- 4. write the snapshot ----------
write('webflow-snapshot/variables.json', [...collections.values()]);
write('webflow-snapshot/styles.json', [...styles.values()].filter((s) => Object.keys(s.properties).length || s.variableModes));
write('webflow-snapshot/source.json', {
  from: 'published-css',
  note: 'Made by `pnpm css:published` from the CSS Webflow publishes, NOT the Webflow MCP. Names and modes are guesses (scripts/css-from-published.mjs lists what it cannot recover). Replace with an MCP snapshot when the connector is available, then delete this file and run pnpm css.',
  site: site ?? null,
  stylesheets: pub.sheets.map((s) => s.url),
  pages: pub.pages.length,
  fetchedAt: new Date().toISOString(),
  assumed: { defaultCollection: DEFAULT_COLLECTION, breakpointModeNames: BP_MODES },
  ...report,
});
const nVars = [...collections.values()].reduce((n, c) => n + c.variables.length, 0);
console.log(`variables.json: ${collections.size} collections, ${nVars} variables (${[...collections.values()].map((c) => `${c.collection} ${c.variables.length}${c.modes.length > 1 ? ` [${c.modes.length} modes]` : ''}`).join('; ')})`);
console.log(`styles.json: ${styles.size} styles; ${report.skippedSelectors.length} selectors and ${report.skippedAtRules.length} at-rules are in webflow.css only (webflow-snapshot/source.json)`);
console.log('Names and modes are guesses: replace the snapshot from the Webflow MCP when it is available. Next: pnpm check:snapshot, pnpm check:drift.');
